package units

import (
	"fmt"
	"strings"

	"github.com/ATCUSA/hamstack/internal/config"
	"github.com/ATCUSA/hamstack/internal/profile"
)

// DirewolfPTT is the PTT line of a Direwolf config. mode is the profile's packet PTT method; device is
// the serial port for rts/dtr; rigPort is the rig's rigctld port for "rig". It returns "" when the
// radio is keyed some other way (VOX), and an error for a mode it cannot honour.
func DirewolfPTT(mode, device string, rigPort int) (string, error) {
	switch mode {
	case "rig":
		if rigPort == 0 {
			return "", fmt.Errorf("keying through rigctld needs a rig with CAT control")
		}
		// Hamlib model 2 is "NET rigctl": Direwolf talks to the rig's rigctld, so the radio has one owner.
		return fmt.Sprintf("PTT RIG 2 localhost:%d", rigPort), nil
	case "rts", "dtr":
		if device == "" {
			return "", fmt.Errorf("keying with %s needs the serial port", strings.ToUpper(mode))
		}
		return fmt.Sprintf("PTT %s %s", device, strings.ToUpper(mode)), nil
	case "cm108":
		return "PTT CM108", nil
	case "none", "":
		return "", nil
	}
	return "", fmt.Errorf("unknown packet PTT method %q (rig, rts, dtr, cm108, none)", mode)
}

// DirewolfConfig returns the direwolf.conf for one rig. audioDevice is the ALSA device resolved right now
// ("" selects ALSA's null device, so Direwolf runs with no sound card); ptt is DirewolfPTT's line.
func DirewolfConfig(rig config.Rig, prof profile.Profile, st config.Station, audioDevice, ptt string) string {
	return DirewolfConfigWith(rig, prof, st, audioDevice, ptt, "")
}

// DirewolfConfigWith is DirewolfConfig with the user's own extra lines (the contents of the rig's direwolf.extra)
// added at the end, where they can override anything above them.
func DirewolfConfigWith(rig config.Rig, prof profile.Profile, st config.Station, audioDevice, ptt, extra string) string {
	agw, kiss := config.DirewolfPorts(rig)
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by hamstack for rig %s (%s). Rewritten every time the service starts.\n", rig.ID, prof.Name)
	if prof.Audio.Null || audioDevice == "" {
		b.WriteString("ADEVICE null null\n")
	} else {
		fmt.Fprintf(&b, "ADEVICE %s %s\n", audioDevice, audioDevice)
	}
	call := st.Callsign
	if rig.Packet.Call != "" {
		call = rig.Packet.Call
	}
	if call == "" {
		call = "N0CALL"
	}
	o := rig.Packet
	fmt.Fprintf(&b, "ACHANNELS 1\nCHANNEL 0\nMYCALL %s\nMODEM %d\n", call, o.ModemBaud())
	for _, kv := range []struct {
		key string
		v   int
	}{{"TXDELAY", o.TxDelay}, {"TXTAIL", o.TxTail}, {"PERSIST", o.Persist}, {"SLOTTIME", o.SlotTime}} {
		if kv.v != 0 {
			fmt.Fprintf(&b, "%s %d\n", kv.key, kv.v)
		}
	}
	if ptt != "" {
		b.WriteString(ptt + "\n")
	}
	if o.Digipeat {
		// The usual APRS digipeater rules: WIDE1-1 and WIDE2-N once each, with a trace of who repeated it.
		b.WriteString("DIGIPEAT 0 0 ^WIDE[3-7]-[1-7]$|^TEST$ ^WIDE[12]-[12]$ TRACE\n")
	}
	// "KISSPORT 0" removes Direwolf's built-in default (8001); without it every Direwolf also listens
	// there, and a second one on the same machine could not start.
	fmt.Fprintf(&b, "AGWPORT %d\nKISSPORT 0\nKISSPORT %d\n", agw, kiss)
	if strings.TrimSpace(extra) != "" {
		fmt.Fprintf(&b, "# Your own lines (%s)\n%s\n", "direwolf.extra", strings.TrimRight(extra, "\n"))
	}
	return b.String()
}
